#!/bin/bash
# Regenerate all patches from a pristine Qt Extended 4.4.3 source tree.
#
# Usage:
#   ./scripts/gen-patches.sh <pristine-root> <modified-root> <output-dir>
#
# pristine-root  : directory containing untouched qt-extended-4.4.3/
# modified-root  : directory containing the patched qt-extended-4.4.3/
# output-dir     : where to write the .patch files (usually patches/)
#
# The generated patches use paths relative to the source root
# (qt-extended-4.4.3/...) and are meant to be applied with `patch -p1`
# from the directory that contains qt-extended-4.4.3/.

set -e
PRISTINE="$1"
MODIFIED="$2"
OUT="$3"

if [ -z "$PRISTINE" ] || [ -z "$MODIFIED" ] || [ -z "$OUT" ]; then
    echo "Usage: $0 <pristine-root> <modified-root> <output-dir>" >&2
    exit 1
fi
mkdir -p "$OUT"

SRC=qt-extended-4.4.3
P="$PRISTINE/$SRC"
M="$MODIFIED/$SRC"

# Each patch: name|file list (space separated, relative to source root)
cat > /tmp/qte_patch_groups.txt <<'GROUPS'
0001-loongarch64-arch|qtopiacore/qt/src/corelib/arch/loongarch64/arch.pri qtopiacore/qt/src/corelib/arch/qatomic_arch.h qtopiacore/qt/src/corelib/arch/generic/qatomic_generic_unix.cpp qtopiacore/qt/mkspecs/linux-g++/qmake.conf qtopiacore/qt/mkspecs/common/g++.conf qtopiacore/qt/mkspecs/qws/linux-loongarch64-g++/qmake.conf qtopiacore/qt/mkspecs/qws/linux-loongarch64-g++/qplatformdefs.h
0002-gcc16-core|qtopiacore/qt/src/corelib/global/qglobal.h qtopiacore/qt/src/network/socket/qnativesocketengine_unix.cpp qtopiacore/qt/src/gui/painting/qpathclipper_p.h qtopiacore/qt/tools/qvfb/qanimationwriter.cpp qtopiacore/qt/src/3rdparty/sqlite/shell.c
0003-vnc-backend|qtopiacore/qt/src/gui/embedded/qscreenvnc_qws.cpp qtopiacore/qt/src/gui/embedded/qscreenvnc_p.h
0004-gcc16-apps|src/3rdparty/libraries/tar/libtar.h src/3rdparty/libraries/openobex/obex_transport.c src/3rdparty/libraries/openobex/obex_object.c src/3rdparty/libraries/openobex/obex.c src/plugins/codecs/wavplay/wavdecoder.cpp src/server/core_server/timeupdateservice.cpp src/libraries/qtopiamail/qmailstore.h src/libraries/qtopia/qphoneprofile.cpp src/libraries/qtopia/qdocumentproperties.cpp src/libraries/qtopiamedia/qmedialist.cpp src/settings/profileedit/ringprofile.cpp src/libraries/qtopiabase/qvaluespace.h src/plugins/cameras/v4lwebcams/webcams.h
GROUPS

while IFS='|' read -r name files; do
    [ -z "$name" ] && continue
    outfile="$OUT/$name.patch"
    : > "$outfile"
    echo "# $name" >> "$outfile"
    echo "# Generated by scripts/gen-patches.sh from Qt Extended 4.4.3 GPL source" >> "$outfile"
    echo "" >> "$outfile"
    for f in $files; do
        old="$P/$f"
        new="$M/$f"
        if [ -f "$old" ]; then
            diff -u "$old" "$new" \
                | sed -e "1s|^--- .*$SRC/|--- $SRC/|" -e "2s|^+++ .*$SRC/|+++ $SRC/|" \
                >> "$outfile" || true
        else
            # New file: diff against /dev/null
            diff -u /dev/null "$new" \
                | sed -e "1s|^--- /dev/null.*|--- /dev/null|" -e "2s|^+++ .*$SRC/|+++ $SRC/|" \
                >> "$outfile" || true
        fi
        echo "" >> "$outfile"
    done
    echo "wrote $outfile ($(wc -l < "$outfile") lines)"
done < /tmp/qte_patch_groups.txt
